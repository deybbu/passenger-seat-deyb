                    </summary>
                    <p>Growing up in a household where food was the centerpiece of every major family gathering, Mariae fell in love with the comforting, communal nature of Filipino hospitality. Long before building her own restaurant brand, she found inspiration in the lively, chaotic energy of the family table—where no one eats until everyone is accounted for. These early memories laid the foundation for an establishment built specifically around sharing massive, hearty feasts with the people who matter most.</p>
                </details>

                <details class="landing-story-chapter">
                    <summary>
                        <span class="landing-story-board-index">02 / INSPIRATION</span>
                        <span class="landing-story-chapter-title">The Flight Attendant Dream &amp; Inspiration</span>
                        <span class="landing-story-read-more-label">Read more</span>
                    </summary>
                    <p>The creative driving force behind Passenger Seat stems from a deeply personal childhood aspiration: Mariae’s lifelong dream of becoming a flight attendant. While life steered her path toward entrepreneurship, her passion for aviation, the hospitality of the skies, and global culinary exploration never faded. To bridge these two worlds, she built a restaurant concept where the service staff are dressed as pilots and flight attendants, turning her ultimate dream into a reality that her guests can experience firsthand.</p>
                </details>

                <details class="landing-story-chapter">
                    <summary>
                        <span class="landing-story-board-index">03 / TAKEOFF</span>
                        <span class="landing-story-chapter-title">The Turning Point</span>
                        <span class="landing-story-read-more-label">Read more</span>
                    </summary>
                    <p>The definitive turning point occurred in 2017 when Mariae decided to launch her first boutique dining venture on Aquilina Street in Marikina City. Wanting to offer something genuinely unique to local foodies, she envisioned a playful space where a passion for travel met the local culinary scene. The overwhelming love from the community triggered massive growth, prompting a successful relocation to the Riverbanks Center and the eventual expansion to SM City San Mateo.</p>
                </details>

                <details class="landing-story-chapter">
